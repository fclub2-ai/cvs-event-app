def run():
    print("=" * 80)
    print("🚀 [1단계] cvs_data.json 카테고리 전수 재분류 시작")
    print("=" * 80)
    
    files = [
        os.path.join(BASE_DIR, "cvs_data.json"),
        os.path.join(BASE_DIR, "backend", "cvs_data.json")
    ]
    
    for fpath in files:
        if not os.path.exists(fpath):
            continue
        with open(fpath, "r", encoding="utf-8") as f:
            data = json.load(f)
            
        changed = 0
        cat_stats = {}
        for p in data.get("products", []):
            old = p.get("category", "")
            new_cat = determine_category_v2(p["name"])
            p["category"] = new_cat
            cat_stats[new_cat] = cat_stats.get(new_cat, 0) + 1
            if old != new_cat:
                changed += 1
                
        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            
        print(f"✅ {os.path.basename(fpath)} 처리 완료:")
        print(f"   - 총 상품 수: {len(data.get('products', []))}개")
        print(f"   - 카테고리 교정된 상품 수: {changed}개")
        print(f"   - 카테고리 분포: {cat_stats}")

    print("\n" + "=" * 80)
    print("🚀 [2단계] index.html에 최신 정제 데이터 번들링 주입")
    print("=" * 80)
    import build_full_bundle
    build_full_bundle.bundle()
    print("✅ index.html 번들링 주입 완료!")

if __name__ == "__main__":
    run()
