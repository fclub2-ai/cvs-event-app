# 2. 데이터 재분류 및 '상품 준비중' 더미 이미지 URL 클리닝
target_files = [
    os.path.join(BASE_DIR, "cvs_data.json"),
    os.path.join(BASE_DIR, "backend", "cvs_data.json")
]

bad_img_keywords = ["no_image", "noimage", "default", "ready", "blank", "empty", "bg_no"]

for fpath in target_files:
    if os.path.exists(fpath):
        with open(fpath, "r", encoding="utf-8") as f:
            data = json.load(f)
        reclassified = 0
        for p in data.get("products", []):
            old = p.get("category", "")
            new_cat = determine_category_v3(p.get("name", ""))
            p["category"] = new_cat
            if old != new_cat:
                reclassified += 1
            
            # 깨진 이미지나 준비중 이미지 URL 정리
            img_url = str(p.get("image", p.get("img", ""))).strip()
            if any(bk in img_url.lower() for bk in bad_img_keywords):
                p["image"] = ""
                
        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✅ {os.path.basename(fpath)} 카테고리 교정 완료! ({reclassified}개 상품 정밀 재분류)")

